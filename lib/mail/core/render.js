"use strict";
/* Renders the five files Postfix and Dovecot read, in full, from the state (D3).

   render(state, hashes, cfg) -> { virtual, vmailbox, sender_login, sasl_access, passwd }
   assertRendered(files, cfg)  -> files, or throws CoreError('backend_failed') with .reason

   Every file is rebuilt from scratch on every change, sorted by key, LF line endings,
   enabled entries only. There is no incremental edit to get wrong, and the daemon's
   reconcile can compare sha256s byte for byte. assertRendered is the last, fail-closed
   gate before anything is written, in the daemon and the mock alike: even a bug in the
   core cannot put a foreign-domain key or a shell metacharacter into a live map. */

const C = require("./constants.js");
const V = require("./validate.js");
const { CoreError } = C;

const FILES = Object.freeze(["virtual", "vmailbox", "sender_login", "sasl_access", "passwd"]);
const DEFAULTS = Object.freeze({ uid: 5000, gid: 5000, homeBase: "/var/vmail/" + C.PINNED_DOMAIN, restrictionClass: "zehnox_sender", mailboxes: true });

const MAP_LINE_RE = /^[a-z0-9._@-]+ [A-Za-z0-9._+=@,/ -]+$/; // no "%": see DEST_RE
const PASSWD_LINE_RE = /^([a-z0-9._@-]+):\{(SHA512-CRYPT|ARGON2ID)\}[A-Za-z0-9./$=,+]+:\d+:\d+::\/var\/vmail\/zehnox\.com\/([a-z0-9._-]+)::$/;
const HEADER_RE = /^# generated by zehnox-maild rev \d+ - do not edit$/;

function header(rev) {
  return "# generated by zehnox-maild rev " + rev + " - do not edit";
}

function render(state, hashes, cfg) {
  const c = Object.assign({}, DEFAULTS, cfg || {});
  if (!Number.isSafeInteger(c.uid) || !Number.isSafeInteger(c.gid) || c.uid < 1 || c.gid < 1) throw new CoreError("backend_failed");
  const lines = { virtual: [], vmailbox: [], sender_login: [], sasl_access: [], passwd: [] };
  const hs = (hashes && hashes.hashes) || {};

  for (const local of Object.keys(state.addresses).sort()) {
    const a = state.addresses[local];
    if (!a.enabled) continue; // a disabled address is in no file: Postfix answers 550 at RCPT
    const key = V.addressOf(local);
    /* c.mailboxes is false while the D10 gate is closed: an existing mailbox then renders
       as forward-only, so no login or local delivery exists until the owner opens it. */
    const box = c.mailboxes && a.mailbox && a.mailbox.enabled && V.hasOwn(hs, local) && typeof hs[local].hash === "string";
    const targets = (box ? [key] : []).concat(a.forwards);
    // A mailbox-only address needs no virtual line: vmailbox delivers it.
    if (a.forwards.length) lines.virtual.push(key + " " + targets.join(", "));
    if (box) {
      lines.vmailbox.push(key + " " + C.PINNED_DOMAIN + "/" + local + "/");
      lines.sender_login.push(key + " " + key);
      lines.sasl_access.push(key + " " + c.restrictionClass);
      lines.passwd.push(key + ":" + hs[local].hash + ":" + c.uid + ":" + c.gid + "::" + c.homeBase + "/" + local + "::");
    }
  }

  const out = {};
  for (const f of FILES) out[f] = [header(state.rev)].concat(lines[f]).join("\n") + "\n";
  return out;
}

function fail(reason) {
  const e = new CoreError("backend_failed");
  e.reason = reason; // a fixed token for the journald line (event=render_assert_failed), never file content
  throw e;
}

function assertRendered(files) {
  if (!files || typeof files !== "object") fail("shape");
  for (const f of FILES) {
    const text = files[f];
    if (typeof text !== "string" || !text.endsWith("\n") || text.includes("\r") || text.includes("\0")) fail("shape:" + f);
    const rows = text.slice(0, -1).split("\n");
    if (!HEADER_RE.test(rows[0])) fail("header:" + f);
    const seen = new Set();
    for (const row of rows.slice(1)) {
      if (f === "passwd") {
        const m = row.match(PASSWD_LINE_RE);
        if (!m) fail("line:" + f);
        if (!C.KEY_RE.test(m[1])) fail("key:" + f);
        // The home directory must be the key's own local part: no sharing, no traversal.
        if (m[3] !== m[1].slice(0, m[1].lastIndexOf("@"))) fail("home:" + f);
        if (seen.has(m[1])) fail("dup:" + f);
        seen.add(m[1]);
        continue;
      }
      if (!MAP_LINE_RE.test(row)) fail("line:" + f);
      const sp = row.indexOf(" ");
      const key = row.slice(0, sp);
      const value = row.slice(sp + 1);
      if (!C.KEY_RE.test(key)) fail("key:" + f);
      if (seen.has(key)) fail("dup:" + f);
      seen.add(key);
      const local = key.slice(0, key.lastIndexOf("@"));
      if (f === "virtual") {
        for (const d of value.split(", ")) if (!V.isDestination(d)) fail("value:" + f);
      } else if (f === "vmailbox") {
        if (value !== C.PINNED_DOMAIN + "/" + local + "/") fail("value:" + f);
      } else if (f === "sender_login") {
        if (value !== key) fail("value:" + f);
      } else if (f === "sasl_access") {
        if (!/^[a-z_]{1,32}$/.test(value)) fail("value:" + f);
      }
    }
  }
  return files;
}

module.exports = { render, assertRendered, FILES, DEFAULTS, header };
