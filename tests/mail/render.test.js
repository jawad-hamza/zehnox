"use strict";
/* Rendering of the five files Postfix and Dovecot read (lib/mail/core/render.js),
   DESIGN.md section 5.5. assertRendered is the last, fail-closed gate before anything is
   written, in the daemon and in the mock: even a core bug cannot put a foreign-domain key
   or a shell/Postfix metacharacter into a live map. */

const test = require("node:test");
const assert = require("node:assert/strict");
const path = require("path");
const crypto = require("crypto");
const { CORE, fakeHash } = require("./helpers/common.js");

const C = require(path.join(CORE, "constants.js"));
const S = require(path.join(CORE, "state.js"));
const R = require(path.join(CORE, "render.js"));
const core = require(path.join(CORE, "core.js"));

const NOW = "2026-09-27T10:00:00.000Z";
const CTX = { now: NOW, capabilities: { mailboxes: true }, hashPolicy: { minRounds: 50000 } };
const codeOf = (fn) => { try { fn(); return null; } catch (e) { return e.code; } };

function build(steps) {
  let st = S.bootstrapState("owner@example.com", NOW);
  let hs = S.emptyHashes();
  for (const [verb, args] of steps) { const r = core.apply(st, hs, verb, args, CTX); st = r.state; hs = r.hashes; }
  return { st, hs };
}

test("golden output: every file, sorted, LF, header with rev, enabled entries only", () => {
  const h = fakeHash(50000);
  const { st, hs } = build([
    ["createAddress", { local: "info", forwards: ["owner@example.com", "ceo@example.com"], mailbox: null, reuseDeleted: false }],
    ["createAddress", { local: "contact", forwards: ["management@example.com"], mailbox: { passwordHash: h }, reuseDeleted: false }],
    ["createAddress", { local: "careers", forwards: [], mailbox: { passwordHash: h }, reuseDeleted: false }],
    ["createAddress", { local: "old", forwards: ["x@example.com"], mailbox: null, reuseDeleted: false }],
    ["setAddressEnabled", { local: "old", enabled: false }],
  ]);
  const f = R.render(st, hs);
  const head = "# generated by zehnox-maild rev " + st.rev + " - do not edit\n";
  assert.equal(f.virtual, head +
    "abuse@zehnox.com owner@example.com\n" +
    "contact@zehnox.com contact@zehnox.com, management@example.com\n" +
    "info@zehnox.com owner@example.com, ceo@example.com\n" +
    "postmaster@zehnox.com owner@example.com\n");
  assert.equal(f.vmailbox, head + "careers@zehnox.com zehnox.com/careers/\ncontact@zehnox.com zehnox.com/contact/\n");
  assert.equal(f.sender_login, head + "careers@zehnox.com careers@zehnox.com\ncontact@zehnox.com contact@zehnox.com\n");
  assert.equal(f.sasl_access, head + "careers@zehnox.com zehnox_sender\ncontact@zehnox.com zehnox_sender\n");
  assert.equal(f.passwd, head +
    "careers@zehnox.com:" + h + ":5000:5000::/var/vmail/zehnox.com/careers::\n" +
    "contact@zehnox.com:" + h + ":5000:5000::/var/vmail/zehnox.com/contact::\n");
  for (const name of R.FILES) assert.ok(!f[name].includes("old@"), "a disabled address is in no file: " + name);
  assert.doesNotThrow(() => R.assertRendered(f));
  assert.deepEqual(R.render(st, hs), f, "deterministic");
});

test("a disabled mailbox, or the closed mailbox gate, renders forward-only", () => {
  const { st, hs } = build([
    ["createAddress", { local: "contact", forwards: ["m@example.com"], mailbox: { passwordHash: fakeHash() }, reuseDeleted: false }],
    ["disableMailbox", { local: "contact" }],
  ]);
  const f = R.render(st, hs);
  assert.match(f.virtual, /^contact@zehnox\.com m@example\.com$/m);
  for (const n of ["vmailbox", "sender_login", "sasl_access", "passwd"]) assert.ok(!f[n].includes("contact@"), n);
  const b = build([["createAddress", { local: "contact", forwards: ["m@example.com"], mailbox: { passwordHash: fakeHash() }, reuseDeleted: false }]]);
  const gated = R.render(b.st, b.hs, { mailboxes: false });
  assert.ok(!gated.passwd.includes("contact@") && !gated.vmailbox.includes("contact@"));
});

test("property: 500 random valid states render only pinned-domain keys and pass assertRendered", () => {
  const rnd = (n) => crypto.randomInt(n);
  const alpha = "abcdefghijklmnopqrstuvwxyz0123456789";
  const local = () => { let s = alpha[rnd(26)]; const n = rnd(12); for (let i = 0; i < n; i++) s += (rnd(6) === 0 ? "._-"[rnd(3)] : "") + alpha[rnd(alpha.length)]; return s; };
  const label = () => { let s = alpha[rnd(26)]; const n = rnd(10); for (let i = 0; i < n; i++) s += alpha[rnd(alpha.length)]; return s; };
  const dest = () => local() + (rnd(3) ? "+" + local() : "") + "@" + label() + ".example." + ["com", "org", "io"][rnd(3)];
  for (let iter = 0; iter < 500; iter++) {
    const st = S.emptyState(NOW);
    const hs = S.emptyHashes();
    st.rev = rnd(1000);
    const n = rnd(8) + 1;
    for (let i = 0; i < n; i++) {
      const l = local();
      if (!C.LOCAL_RE.test(l) || st.addresses[l]) continue;
      const box = rnd(2) === 0;
      const forwards = Array.from({ length: box ? rnd(3) : rnd(3) + 1 }, dest);
      st.addresses[l] = { forwards, enabled: rnd(5) !== 0, mailbox: box ? { enabled: rnd(4) !== 0 } : null, protected: false, createdAt: NOW, updatedAt: NOW };
      if (box) hs.hashes[l] = { hash: fakeHash(50000 + rnd(1000)), passwordSetAt: NOW };
    }
    const f = R.assertRendered(R.render(st, hs));
    for (const name of R.FILES) {
      for (const line of f[name].split("\n").slice(1).filter(Boolean)) {
        const key = name === "passwd" ? line.slice(0, line.indexOf(":")) : line.slice(0, line.indexOf(" "));
        assert.match(key, C.KEY_RE, name + ": " + line);
        assert.ok(key.endsWith("@zehnox.com"));
      }
    }
  }
});

test("assertRendered refuses a foreign domain, forbidden characters, bad homes and duplicates", () => {
  const { st, hs } = build([["createAddress", { local: "contact", forwards: ["m@example.com"], mailbox: { passwordHash: fakeHash() }, reuseDeleted: false }]]);
  const good = R.render(st, hs);
  const tamper = (file, fn) => Object.assign({}, good, { [file]: fn(good[file]) });
  const bad = [
    tamper("virtual", (t) => t + "info@strategicbhm.com owner@example.com\n"),
    tamper("virtual", (t) => t + "info@zehnox.com.evil.com owner@example.com\n"),
    tamper("virtual", (t) => t + "INFO@zehnox.com owner@example.com\n"),
    tamper("virtual", (t) => t + "info@zehnox.com |/bin/sh\n"),
    tamper("virtual", (t) => t + "info@zehnox.com :include:/etc/passwd\n"),
    tamper("virtual", (t) => t + "info@zehnox.com a@x.com;id\n"),
    tamper("virtual", (t) => t + "info@zehnox.com a@x.com\r\n"),
    tamper("virtual", (t) => t + "info@zehnox.com a@x.com\0\n"),
    tamper("virtual", (t) => t + "abuse@zehnox.com dup@example.com\n"),
    tamper("virtual", (t) => t.replace(/^# generated.*$/m, "# hand edited")),
    tamper("virtual", (t) => t.slice(0, -1)),
    tamper("vmailbox", (t) => t.replace("zehnox.com/contact/", "zehnox.com/../root/")),
    tamper("vmailbox", (t) => t.replace("zehnox.com/contact/", "strategicbhm.com/contact/")),
    tamper("sender_login", (t) => t.replace("contact@zehnox.com contact@zehnox.com", "contact@zehnox.com ceo@strategicbhm.com")),
    tamper("sasl_access", (t) => t.replace("zehnox_sender", "permit mynetworks")),
    tamper("passwd", (t) => t.replace("/var/vmail/zehnox.com/contact::", "/var/vmail/zehnox.com/other::")),
    tamper("passwd", (t) => t.replace("/var/vmail/zehnox.com/contact::", "/etc::")),
    tamper("passwd", (t) => t.replace("{SHA512-CRYPT}", "{PLAIN}")),
    tamper("passwd", (t) => t.replace("contact@zehnox.com:", "contact@strategicbhm.com:")),
    tamper("passwd", (t) => t + t.split("\n")[1] + "\n"),
    Object.assign({}, good, { passwd: undefined }),
    null,
  ];
  for (const [i, f] of bad.entries()) {
    assert.equal(codeOf(() => R.assertRendered(f)), "backend_failed", "case " + i);
  }
  // The failure reason is a fixed token, never file content.
  try { R.assertRendered(bad[0]); } catch (e) { assert.match(e.reason, /^[a-z_]+(:[a-z_]+)?$/); assert.ok(!String(e.message).includes("strategicbhm")); }
});

test("render refuses a nonsense uid/gid instead of writing it", () => {
  const { st, hs } = build([]);
  assert.equal(codeOf(() => R.render(st, hs, { uid: 0 })), "backend_failed");
  assert.equal(codeOf(() => R.render(st, hs, { gid: "5000;id" })), "backend_failed");
});
